/// Statistical summary containing mean, sample standard deviation, and variance metrics.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StatSummary {
    pub mean: f64,
    pub std_dev: f64,
    pub cv_pct: f64,
    pub min: f64,
    pub max: f64,
    pub range: f64,
}

impl StatSummary {
    pub fn calculate(values: &[f64]) -> Self {
        let n = values.len();
        if n == 0 {
            return Self {
                mean: 0.0,
                std_dev: 0.0,
                cv_pct: 0.0,
                min: 0.0,
                max: 0.0,
                range: 0.0,
            };
        }
        let mean = values.iter().copied().sum::<f64>() / n as f64;
        let std_dev = if n > 1 {
            let variance = values.iter().map(|&x| (x - mean).powi(2)).sum::<f64>() / (n - 1) as f64;
            variance.sqrt()
        } else {
            0.0
        };
        let cv_pct = if mean.abs() > 1e-9 {
            (std_dev / mean) * 100.0
        } else {
            0.0
        };
        let min = values.iter().copied().fold(f64::INFINITY, f64::min);
        let max = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        let range = max - min;

        Self {
            mean,
            std_dev,
            cv_pct,
            min,
            max,
            range,
        }
    }
}

/// Stability metrics for an individual scene/act across all runs.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SceneConsistencyStats {
    pub scene_id: u32,
    pub scene_name: String,
    pub fps_stats: StatSummary,
    pub frametime_stats: StatSummary,
}

/// Comprehensive report generated by the consistency & thermal stability suite.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConsistencyReport {
    pub timestamp: String,
    pub system_info: SystemReport,
    pub iterations_completed: usize,
    pub cooldown_seconds: u64,
    pub frames_per_scene: u32,
    pub resolution: String,
    pub score_stats: StatSummary,
    pub duration_stats: StatSummary,
    pub peak_gpu_temp_stats: StatSummary,
    pub peak_hotspot_stats: StatSummary,
    pub peak_clock_stats: StatSummary,
    pub peak_power_stats: StatSummary,
    pub scene_stats: Vec<SceneConsistencyStats>,
    #[serde(default)]
    pub gpu_telemetry: Option<super::telemetry::GpuTelemetryAssessment>,
    pub runs: Vec<BenchmarkReport>,
}

/// Computes consistency statistics across a slice of benchmark reports.
pub fn compute_consistency_report(
    runs: &[BenchmarkReport],
    cooldown_seconds: u64,
    frames_per_scene: u32,
    resolution: &str,
) -> ConsistencyReport {
    if runs.is_empty() {
        return ConsistencyReport {
            timestamp: "empty".to_string(),
            system_info: SystemReport {
                gpu_name: String::new(),
                gpu_backend: String::new(),
                gpu_driver: String::new(),
                cpu_name: String::new(),
                cpu_threads: 0,
            },
            iterations_completed: 0,
            cooldown_seconds,
            frames_per_scene,
            resolution: resolution.to_string(),
            score_stats: StatSummary::calculate(&[]),
            duration_stats: StatSummary::calculate(&[]),
            peak_gpu_temp_stats: StatSummary::calculate(&[]),
            peak_hotspot_stats: StatSummary::calculate(&[]),
            peak_clock_stats: StatSummary::calculate(&[]),
            peak_power_stats: StatSummary::calculate(&[]),
            scene_stats: Vec::new(),
            gpu_telemetry: None,
            runs: Vec::new(),
        };
    }

    let first = &runs[0];
    let scores: Vec<f64> = runs.iter().map(|r| r.overall_score).collect();
    let durations: Vec<f64> = runs.iter().map(|r| r.total_elapsed_seconds).collect();
    let temps: Vec<f64> = runs.iter().map(|r| r.peak_gpu_temp_c as f64).collect();
    let hotspots: Vec<f64> = runs.iter().map(|r| r.peak_gpu_hotspot_c as f64).collect();
    let clocks: Vec<f64> = runs.iter().map(|r| r.peak_gpu_clock_mhz as f64).collect();
    let powers: Vec<f64> = runs.iter().map(|r| r.peak_gpu_power_w as f64).collect();

    let score_stats = StatSummary::calculate(&scores);
    let duration_stats = StatSummary::calculate(&durations);
    let peak_gpu_temp_stats = StatSummary::calculate(&temps);
    let peak_hotspot_stats = StatSummary::calculate(&hotspots);
    let peak_clock_stats = StatSummary::calculate(&clocks);
    let peak_power_stats = StatSummary::calculate(&powers);

    // Group scene stats across runs
    let scene_count = first.scene_results.len();
    let mut scene_stats = Vec::with_capacity(scene_count);

    for s_idx in 0..scene_count {
        let scene_name = &first.scene_results[s_idx].scene_name;
        let scene_id = first.scene_results[s_idx].scene_id;

        let fps_vals: Vec<f64> = runs
            .iter()
            .filter_map(|r| r.scene_results.get(s_idx).map(|s| s.avg_fps))
            .collect();

        let ft_vals: Vec<f64> = runs
            .iter()
            .filter_map(|r| r.scene_results.get(s_idx).map(|s| s.avg_frametime_ms))
            .collect();

        scene_stats.push(SceneConsistencyStats {
            scene_id,
            scene_name: scene_name.clone(),
            fps_stats: StatSummary::calculate(&fps_vals),
            frametime_stats: StatSummary::calculate(&ft_vals),
        });
    }

    // Evaluate aggregate GPU telemetry across all iterations
    let all_snapshots: Vec<super::telemetry::TelemetrySnapshot> = runs
        .iter()
        .flat_map(|r| r.telemetry_samples.clone())
        .collect();

    let gpu_telemetry = if !all_snapshots.is_empty() {
        if let Some(last_run) = runs.last() {
            let stats = crate::telemetry::HardwareStats {
                gpu_name: last_run.system_info.gpu_name.clone(),
                gpu_clock_mhz: last_run.peak_gpu_clock_mhz,
                gpu_mem_clock_mhz: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.mem_clock_mhz.max as u32)
                    .unwrap_or(0),
                gpu_voltage_mv: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.core_voltage_mv.max as u32)
                    .unwrap_or(0),
                gpu_util_pct: last_run.peak_gpu_util_pct,
                mem_util_pct: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.mem_util_pct.max)
                    .unwrap_or(0.0),
                gpu_temp_c: last_run.peak_gpu_temp_c,
                gpu_hotspot_c: last_run.peak_gpu_hotspot_c,
                gpu_mem_temp_c: last_run
                    .gpu_telemetry
                    .as_ref()
                    .and_then(|t| t.mem_temp_c.as_ref())
                    .map(|m| m.max)
                    .unwrap_or(0.0),
                gpu_temp_crit_c: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.temp_crit_c)
                    .unwrap_or(0.0),
                gpu_hotspot_crit_c: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.hotspot_crit_c)
                    .unwrap_or(0.0),
                gpu_fan_rpm: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.fan_rpm.max as u32),
                gpu_fan_max_rpm: None,
                gpu_fan_pwm: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| ((t.peak_fan_pwm_pct / 100.0) * 255.0) as u32),
                gpu_power_w: last_run.peak_gpu_power_w,
                gpu_power_cap_w: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.power_cap_w)
                    .unwrap_or(0.0),
                vram_used_mb: last_run.peak_vram_mb,
                vram_total_mb: 0,
                vram_vendor: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.vram_vendor.clone())
                    .unwrap_or_default(),
                pcie_link: last_run
                    .gpu_telemetry
                    .as_ref()
                    .map(|t| t.pcie_link.clone())
                    .unwrap_or_default(),
                cpu_name: last_run.system_info.cpu_name.clone(),
                cpu_usage_pct: 0.0,
                cpu_threads: last_run.system_info.cpu_threads,
                peak_gpu_clock_mhz: last_run.peak_gpu_clock_mhz,
                peak_gpu_util_pct: last_run.peak_gpu_util_pct,
                gpu_mem_temp_crit_c: 0.0,
                ..Default::default()
            };
            Some(super::telemetry::GpuTelemetryAssessment::evaluate(
                &all_snapshots,
                &stats,
            ))
        } else {
            None
        }
    } else {
        runs.last().and_then(|r| r.gpu_telemetry.clone())
    };

    ConsistencyReport {
        timestamp: first.timestamp.clone(),
        system_info: first.system_info.clone(),
        iterations_completed: runs.len(),
        cooldown_seconds,
        frames_per_scene,
        resolution: resolution.to_string(),
        score_stats,
        duration_stats,
        peak_gpu_temp_stats,
        peak_hotspot_stats,
        peak_clock_stats,
        peak_power_stats,
        scene_stats,
        gpu_telemetry,
        runs: runs.to_vec(),
    }
}

/// Returns a descriptive rating label based on the coefficient of variation (CV%).
pub fn consistency_grade(cv_pct: f64) -> (&'static str, &'static str) {
    if cv_pct <= 0.25 {
        ("EXEMPLARY (CV < 0.25%)", "\x1b[38;2;0;255;128;1m")
    } else if cv_pct <= 0.75 {
        ("EXCELLENT (CV < 0.75%)", "\x1b[38;2;0;220;255;1m")
    } else if cv_pct <= 1.50 {
        ("VERY GOOD (CV < 1.50%)", "\x1b[38;2;255;220;0;1m")
    } else if cv_pct <= 3.00 {
        ("STABLE (CV < 3.00%)", "\x1b[38;2;255;160;0;1m")
    } else {
        ("HIGH VARIANCE (CV > 3.00%)", "\x1b[38;2;255;80;80;1m")
    }
}

/// Formats the consistency report into a terminal ANSI box scorecard.
pub fn format_consistency_scorecard(report: &ConsistencyReport) -> String {
    let mut out = String::with_capacity(4096);

    out.push_str("\n\x1b[38;2;0;220;255;1m┌──────────────────────────────────────────────────────────────────────────┐\n");
    out.push_str("│             DYNO_TERM CONSISTENCY & THERMAL STABILITY SCORECARD          │\n");
    out.push_str(
        "├──────────────────────────────────────────────────────────────────────────┤\x1b[0m\n",
    );

    let gpu_info = format!(
        "{} ({})",
        report.system_info.gpu_name, report.system_info.gpu_backend
    );
    let cpu_info = format!(
        "{} ({} Threads)",
        report.system_info.cpu_name, report.system_info.cpu_threads
    );
    let run_info = format!(
        "{} Iterations │ {}s Cooldown Pause",
        report.iterations_completed, report.cooldown_seconds
    );

    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ GPU: \x1b[38;2;255;255;255;1m{:<67}\x1b[38;2;0;220;255m│\n",
        truncate_str(&gpu_info, 67)
    ));
    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ CPU: \x1b[38;2;255;255;255;1m{:<67}\x1b[38;2;0;220;255m│\n",
        truncate_str(&cpu_info, 67)
    ));
    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ Mode: \x1b[38;2;0;255;200;1m{:<29}\x1b[38;2;140;150;170m│ Target: \x1b[38;2;255;180;0;1m{:<27}\x1b[38;2;0;220;255m│\n",
        truncate_str(&run_info, 29),
        truncate_str(&report.resolution, 27)
    ));
    out.push_str("\x1b[38;2;0;220;255m├──────────────────────────────────────────────────────────────────────────┤\x1b[0m\n");

    // Table of individual runs
    out.push_str("\x1b[38;2;140;150;170m│ \x1b[1mRUN  │ TIME     │ OVERALL SCORE │ PEAK TEMP │ HOTSPOT  │ CLOCK    │ POWER  \x1b[0m\x1b[38;2;0;220;255m│\n");
    out.push_str("\x1b[38;2;0;220;255m├──────┼──────────┼───────────────┼───────────┼──────────┼──────────┼────────┤\x1b[0m\n");

    for (i, run) in report.runs.iter().enumerate() {
        let run_num = format!("#{}", i + 1);
        let time_str = format!("{:>5.2}s", run.total_elapsed_seconds);
        let score_str = format!("{:>8.2} pts", run.overall_score);
        let temp_str = format!("{:>4.0}°C", run.peak_gpu_temp_c);
        let hot_str = format!("{:>4.0}°C", run.peak_gpu_hotspot_c);
        let clock_str = format!("{:>4}MHz", run.peak_gpu_clock_mhz);
        let power_str = format!("{:>3.0}W", run.peak_gpu_power_w);

        out.push_str(&format!(
            "\x1b[38;2;140;150;170m│ \x1b[38;2;255;180;0;1m{:<4}\x1b[38;2;140;150;170m │ \x1b[38;2;255;255;255m{:<8}\x1b[38;2;140;150;170m │ \x1b[38;2;0;255;200;1m{:<13}\x1b[38;2;140;150;170m │ \x1b[38;2;255;255;255m{:<9}\x1b[38;2;140;150;170m │ \x1b[38;2;255;255;255m{:<8}\x1b[38;2;140;150;170m │ \x1b[38;2;255;255;255m{:<8}\x1b[38;2;140;150;170m │ \x1b[38;2;255;255;255m{:<6}\x1b[38;2;140;150;170m │\x1b[0m\n",
            run_num, time_str, score_str, temp_str, hot_str, clock_str, power_str
        ));
    }

    out.push_str("\x1b[38;2;0;220;255m├──────────────────────────────────────────────────────────────────────────┤\x1b[0m\n");

    // Aggregate statistics
    let (grade_str, grade_color) = consistency_grade(report.score_stats.cv_pct);
    let mean_score_fmt = format!("{:.2} pts", report.score_stats.mean);
    let std_score_fmt = format!(
        "±{:.2} pts ({:.3}% CV)",
        report.score_stats.std_dev, report.score_stats.cv_pct
    );
    let spread_pct = if report.score_stats.mean > 0.0 {
        (report.score_stats.range / report.score_stats.mean) * 100.0
    } else {
        0.0
    };
    let spread_fmt = format!(
        "{:.2} pts ({:.3}% delta)",
        report.score_stats.range, spread_pct
    );

    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ Mean Score: \x1b[38;2;255;180;0;1m{:<22}\x1b[38;2;140;150;170m │ Std Dev: \x1b[38;2;0;255;200;1m{:<24}\x1b[38;2;0;220;255m│\n",
        mean_score_fmt, std_score_fmt
    ));
    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ Total Spread: \x1b[38;2;255;255;255;1m{:<20}\x1b[38;2;140;150;170m │ Grade: {}{:<26}\x1b[38;2;0;220;255m│\n",
        spread_fmt, grade_color, grade_str
    ));
    out.push_str("\x1b[38;2;0;220;255m├──────────────────────────────────────────────────────────────────────────┤\x1b[0m\n");

    // Per-Act FPS Stability
    out.push_str("\x1b[38;2;140;150;170m│ \x1b[1mPER-ACT FPS STABILITY          │ MEAN FPS  │ STD DEV  │ CV (%)  │ SPREAD  \x1b[0m\x1b[38;2;0;220;255m│\n");
    out.push_str("\x1b[38;2;0;220;255m├────────────────────────────────┼───────────┼──────────┼─────────┼─────────┤\x1b[0m\n");

    for s in &report.scene_stats {
        let name_trimmed = truncate_str(&s.scene_name, 30);
        let mean_fps_str = format!("{:>7.1} FPS", s.fps_stats.mean);
        let std_fps_str = format!("±{:>5.2}", s.fps_stats.std_dev);
        let cv_str = format!("{:>5.2}%", s.fps_stats.cv_pct);
        let spread_str = format!("{:>5.2}", s.fps_stats.range);

        out.push_str(&format!(
            "\x1b[38;2;140;150;170m│ \x1b[38;2;255;255;255;1m{:<30} \x1b[38;2;0;220;255m│ \x1b[38;2;0;255;200;1m{:<9} \x1b[38;2;0;220;255m│ \x1b[38;2;255;255;255m{:<8} \x1b[38;2;0;220;255m│ \x1b[38;2;255;180;0;1m{:<7} \x1b[38;2;0;220;255m│ \x1b[38;2;255;255;255m{:<7} \x1b[38;2;0;220;255m│\n",
            name_trimmed, mean_fps_str, std_fps_str, cv_str, spread_str
        ));
    }

    out.push_str("\x1b[38;2;0;220;255m├──────────────────────────────────────────────────────────────────────────┤\x1b[0m\n");

    // Thermal & Clock drift
    let thermal_drift = report.peak_gpu_temp_stats.range;
    let clock_drift = report.peak_clock_stats.range;
    let thermal_summary = format!(
        "Core: {:.0}°C (±{:.1}°C) │ Hotspot: {:.0}°C │ Boost: {:.0}MHz (±{:.0}MHz) │ Drift: {:.0}°C",
        report.peak_gpu_temp_stats.mean,
        thermal_drift,
        report.peak_hotspot_stats.mean,
        report.peak_clock_stats.mean,
        clock_drift,
        thermal_drift
    );
    let vis_len = crate::terminal::visible_len(&thermal_summary);
    let pad_len = 72usize.saturating_sub(vis_len);

    out.push_str(&format!(
        "\x1b[38;2;140;150;170m│ {}{}\x1b[38;2;0;220;255m│\n",
        thermal_summary,
        " ".repeat(pad_len)
    ));
    if let Some(ref assessment) = report.gpu_telemetry {
        out.push_str(&super::telemetry::format_gpu_assessment_box(assessment));
    }
    out.push_str("\x1b[38;2;0;220;255;1m└──────────────────────────────────────────────────────────────────────────┘\x1b[0m\n");

    out
}

/// Saves the consistency report to a JSON file.
pub fn save_consistency_report<P: AsRef<Path>>(
    report: &ConsistencyReport,
    path: P,
) -> std::io::Result<()> {
    let json =
        serde_json::to_string_pretty(report).map_err(|e| std::io::Error::other(e.to_string()))?;
    fs::write(path, json)
}

/// Loads a consistency report from a JSON file.
pub fn load_consistency_report<P: AsRef<Path>>(path: P) -> Option<ConsistencyReport> {
    let content = fs::read_to_string(path).ok()?;
    serde_json::from_str(&content).ok()
}

fn truncate_str(s: &str, max_len: usize) -> String {
    if s.chars().count() <= max_len {
        s.to_string()
    } else {
        let mut truncated: String = s.chars().take(max_len.saturating_sub(1)).collect();
        truncated.push('…');
        truncated
    }
}

