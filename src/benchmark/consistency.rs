    #[test]
    fn test_stat_summary_calculation() {
        // [100.0, 102.0, 98.0] -> mean = 100.0, variance = ((0)^2 + (2)^2 + (-2)^2)/2 = 8/2 = 4, std_dev = 2.0, cv = 2.0%
        let values = [100.0, 102.0, 98.0];
        let stats = StatSummary::calculate(&values);
        assert!((stats.mean - 100.0).abs() < 1e-6);
        assert!((stats.std_dev - 2.0).abs() < 1e-6);
        assert!((stats.cv_pct - 2.0).abs() < 1e-6);
        assert_eq!(stats.min, 98.0);
        assert_eq!(stats.max, 102.0);
        assert_eq!(stats.range, 4.0);
    }

